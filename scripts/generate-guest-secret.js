/**
 * Generates the HMAC secret used to sign guest session cookies, into `.env`.
 *
 * Written straight to the file rather than printed, so the secret never appears in
 * a terminal log. Refuses to overwrite: rotating it invalidates every guest
 * session, ejecting anyone currently in a room as a guest.
 */
const crypto = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");

const ENV_PATH = path.resolve(process.cwd(), ".env");

const existing = fs.existsSync(ENV_PATH)
  ? fs.readFileSync(ENV_PATH, "utf8")
  : "";

if (existing.includes("GUEST_SESSION_SECRET=")) {
  console.log(
    "GUEST_SESSION_SECRET already present in .env — leaving it alone. Delete the line first if you really want to rotate.",
  );
  process.exit(0);
}

const secret = crypto.randomBytes(48).toString("base64url");

const block = [
  "",
  "# Signs the short-lived cookie that lets a guest without an account stay in a",
  "# room after entering the passcode. Generated by scripts/generate-guest-secret.js.",
  "# Rotating this ejects every current guest.",
  `GUEST_SESSION_SECRET=${secret}`,
  "",
].join("\n");

const needsNewline = existing.length > 0 && !existing.endsWith("\n");

fs.appendFileSync(ENV_PATH, `${needsNewline ? "\n" : ""}${block}`);

console.log("Wrote GUEST_SESSION_SECRET to .env. The value was not printed.");
